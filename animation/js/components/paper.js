/* =============================================================================
   Paper visual system
   - SVG <defs>: paper filters (cut-edge wobble + soft cast shadow), texture
     patterns, shared gradients.
   - PaperShape / PaperShadow / PaperLabel building blocks.
   Colours come from CSS variables in styles.css (used through `style="fill:
   var(--x)"`, because SVG presentation attributes cannot read var()).
   ========================================================================== */
(function () {
  const { el, g } = GB;

  const C = (name) => `var(--${name})`;
  GB.C = C;

  function cssNum(name, fallback) {
    const v = parseFloat(getComputedStyle(document.documentElement).getPropertyValue('--' + name));
    return isNaN(v) ? fallback : v;
  }
  GB.cssNum = cssNum;

  // Textures (generated by tools/make-textures.py). `s` = display scale.
  GB.TEXTURES = {
    fibre: { src: 'assets/paper-textures/fibre.png', size: 512, s: 1 },
    hurds: { src: 'assets/paper-textures/hurds.png', size: 512, s: 0.9 },
    mix: { src: 'assets/paper-textures/mix.png', size: 512, s: 0.9 },
    mixGrown: { src: 'assets/paper-textures/mix-grown.png', size: 512, s: 0.9 },
    grobox: { src: 'assets/paper-textures/grobox-material.png', size: 512, s: 0.75 },
    eps: { src: 'assets/paper-textures/eps-foam.png', size: 256, s: 0.8 },
    soil: { src: 'assets/paper-textures/soil.png', size: 384, s: 1 }
  };

  /** Build all shared <defs>. Called once at boot (after CSS is loaded). */
  GB.buildDefs = function (svg) {
    const defs = el('defs', {}, svg);
    GB.defs = defs;
    const depth = cssNum('shadow-depth', 1);
    const fast = GB.config.quality === 'fast';
    const sh = cssNum('shadow-opacity', 0.26);

    // --- textures as patterns
    for (const id in GB.TEXTURES) {
      const t = GB.TEXTURES[id];
      const s = t.size * t.s;
      const p = el('pattern', { id: 'p-' + id, patternUnits: 'userSpaceOnUse', width: s, height: s }, defs);
      el('image', { href: t.src, width: s, height: s, preserveAspectRatio: 'none' }, p);
    }

    // --- filters
    const mk = (id, opts) => {
      const fl = el('filter', { id, x: '-20%', y: '-20%', width: '140%', height: '150%', 'color-interpolation-filters': 'sRGB' }, defs);
      let src = 'SourceGraphic';
      if (opts.rough) {
        el('feTurbulence', { type: 'fractalNoise', baseFrequency: opts.freq || 0.04, numOctaves: 2, seed: opts.seed || 4, result: 'noise' }, fl);
        el('feDisplacementMap', { in: 'SourceGraphic', in2: 'noise', scale: opts.rough, xChannelSelector: 'R', yChannelSelector: 'G', result: 'cut' }, fl);
        src = 'cut';
      }
      if (opts.blur) {
        el('feGaussianBlur', { in: src, stdDeviation: fast ? 0 : opts.blur }, fl);
        return fl;
      }
      if (opts.shadow) {
        const [dx, dy, b, o] = opts.shadow;
        el('feGaussianBlur', { in: src === 'cut' ? 'cut' : 'SourceAlpha', stdDeviation: fast ? 0 : b * depth, result: 'blur' }, fl);
        el('feOffset', { in: 'blur', dx: dx * depth, dy: dy * depth, result: 'off' }, fl);
        el('feFlood', { 'flood-color': '#3a2a18', 'flood-opacity': o * sh / 0.26 }, fl);
        el('feComposite', { in2: 'off', operator: 'in', result: 'shadow' }, fl);
        const m = el('feMerge', {}, fl);
        el('feMergeNode', { in: 'shadow' }, m);
        el('feMergeNode', { in: src }, m);
      }
      return fl;
    };
    mk('f-paper', { shadow: [1, 3, 2.5, 0.30] });                 // flat paper piece on the table
    mk('f-paper-rough', { rough: 3, shadow: [1, 3, 2.5, 0.30] });  // hand-cut organic piece
    mk('f-lift', { shadow: [3, 12, 9, 0.22] });                    // raised / floating piece
    mk('f-lift-rough', { rough: 3, shadow: [3, 12, 9, 0.22] });
    mk('f-thread', { shadow: [0.6, 1.4, 0.9, 0.45] });             // mycelium thread
    mk('f-rough', { rough: 2.5 });
    mk('f-blur-s', { blur: 3 });
    mk('f-blur-m', { blur: 8 });
    mk('f-blur-l', { blur: 18 });

    // --- shared gradients
    GB.linGrad('g-band-beige', [[0, '#cdb58c'], [0.12, '#dcc59c'], [0.5, '#e3cfa8'], [0.88, '#d8c197'], [1, '#c6ad82']]);
    GB.linGrad('g-band-grey', [[0, '#7f8284'], [0.12, '#909395'], [0.5, '#999c9e'], [0.88, '#8d9092'], [1, '#7a7d80']]);
    GB.linGrad('g-band-white', [[0, '#dcdcda'], [0.12, '#ecebe8'], [0.5, '#f2f1ee'], [0.88, '#e9e8e5'], [1, '#d6d6d3']]);
    GB.linGrad('g-inner-shade', [[0, 'rgba(60,40,20,0.30)'], [0.55, 'rgba(60,40,20,0.08)'], [1, 'rgba(60,40,20,0)']], 0, 0, 0, 1);
    GB.radGrad('g-vignette', [[0, 'rgba(0,0,0,0)'], [0.65, 'rgba(0,0,0,0)'], [1, 'rgba(60,45,25,0.20)']]);
    GB.radGrad('g-glow-warm', [[0, 'rgba(255,190,120,0.55)'], [1, 'rgba(255,190,120,0)']]);
    GB.radGrad('g-contact', [[0, 'rgba(50,35,20,0.35)'], [1, 'rgba(50,35,20,0)']]);
    return defs;
  };

  GB.linGrad = function (id, stops, x1 = 0, y1 = 0, x2 = 1, y2 = 0) {
    const lg = el('linearGradient', { id, x1, y1, x2, y2 }, GB.defs);
    for (const [o, c, op] of stops) el('stop', { offset: o, style: `stop-color:${c};stop-opacity:${op === undefined ? 1 : op}` }, lg);
    return lg;
  };
  GB.radGrad = function (id, stops) {
    const rg = el('radialGradient', { id, cx: 0.5, cy: 0.5, r: 0.5 }, GB.defs);
    for (const [o, c] of stops) el('stop', { offset: o, style: `stop-color:${c}` }, rg);
    return rg;
  };

  /** Resolve colour tokens: '@kraft' → var(--kraft); 'url(...)' / '#hex' as-is. */
  function paint(c) {
    if (!c) return 'none';
    if (c[0] === '@') return C(c.slice(1));
    if (c[0] === '#' && c.length > 1 && c[1] === '#') return c.slice(1);
    if (c.startsWith('p-') || c.startsWith('g-')) return `url(#${c})`;
    return c;
  }
  GB.paint = paint;

  /**
   * PaperShape — a cut piece of paper.
   *   GB.PaperShape(parent, d, fill, { filter, texture, textureOpacity, stroke, strokeWidth, opacity })
   * filter: 'paper' | 'paper-rough' | 'lift' | 'lift-rough' | null
   * texture: true (fibre overlay) | pattern key ('p-hurds') | false
   */
  GB.PaperShape = function (parent, d, fill, o) {
    o = o || {};
    const grp = g(parent, o.filter ? { filter: `url(#f-${o.filter})` } : {});
    const base = el('path', { d, style: `fill:${paint(fill)}` + (o.stroke ? `;stroke:${paint(o.stroke)};stroke-width:${o.strokeWidth || 2}` : '') }, grp);
    grp.shape = base;
    const tex = o.texture === undefined ? true : o.texture;
    if (tex) {
      const pid = tex === true ? 'p-fibre' : tex;
      grp.tex = el('path', { d, style: `fill:url(#${pid});opacity:${o.textureOpacity === undefined ? 'var(--texture-intensity)' : o.textureOpacity}`, 'pointer-events': 'none' }, grp);
      if (o.blend) grp.tex.style.mixBlendMode = o.blend;
    }
    if (o.opacity !== undefined) grp.setAttribute('opacity', o.opacity);
    grp.setD = function (nd) { base.setAttribute('d', nd); if (grp.tex) grp.tex.setAttribute('d', nd); };
    return grp;
  };

  /** Simple flat path (no texture / filter) — for small details. */
  GB.path = function (parent, d, fill, extra) {
    const st = `fill:${paint(fill)}` + (extra && extra.stroke ? `;stroke:${paint(extra.stroke)};stroke-width:${extra.sw || 2};stroke-linecap:round;stroke-linejoin:round` : '');
    const p = el('path', { d, style: st }, parent);
    if (extra && extra.opacity !== undefined) p.setAttribute('opacity', extra.opacity);
    return p;
  };
  GB.line = function (parent, d, stroke, sw, extra) {
    return el('path', Object.assign({ d, style: `fill:none;stroke:${paint(stroke)};stroke-width:${sw};stroke-linecap:round;stroke-linejoin:round` }, extra || {}), parent);
  };

  /** PaperShadow — soft contact shadow on the table under an object. */
  GB.PaperShadow = function (parent, cx, cy, rx, ry, opacity) {
    return el('ellipse', { cx, cy, rx, ry, style: `fill:url(#g-contact);opacity:${opacity === undefined ? 0.9 : opacity}` }, parent);
  };

  /** Stage background (paper sheet) — full frame. */
  GB.PaperBackdrop = function (parent, fill) {
    const r = el('rect', { x: -400, y: -300, width: 2720, height: 1680, style: `fill:${paint(fill || '@paper')}` }, parent);
    return r;
  };

  /**
   * PaperLabel — a small hand-cut paper tag with text (captions, legends).
   * Returns a group; width is measured once fonts are loaded.
   */
  GB.PaperLabel = function (parent, text, o) {
    o = o || {};
    const size = o.size || 40;
    const grp = g(parent, { class: 'paper-label' });
    const card = el('path', { style: `fill:${paint(o.fill || '@card')}`, filter: 'url(#f-paper)' }, grp);
    const tx = el('text', { x: 0, y: 0, 'font-size': size, class: o.className || 'cap-text', style: `fill:${paint(o.color || '@ink')}` }, grp);
    tx.textContent = text;
    let sub;
    if (o.sub) {
      sub = el('text', { x: 0, y: size * 1.05, 'font-size': size * 0.58, class: 'cap-sub', style: `fill:${paint('@ink-soft')}` }, grp);
      sub.textContent = o.sub;
    }
    grp.layout = function () {
      const w = Math.max(tx.getComputedTextLength(), sub ? sub.getComputedTextLength() : 0);
      const padX = size * 0.62, padY = size * 0.48;
      const h = size * (sub ? 1.95 : 1.15);
      const x0 = -padX, y0 = -size * 0.92 - padY * 0.4, W = w + padX * 2, H = h + padY;
      const r = GB.rng(GB.hash(text));
      const j = () => (r() - 0.5) * 3;
      card.setAttribute('d', GB.polyPath([[x0 + j(), y0 + j()], [x0 + W + j(), y0 + j()], [x0 + W + j(), y0 + H + j()], [x0 + j(), y0 + H + j()]]));
      grp.w = W; grp.h = H; grp.bottom = y0 + H; grp.left = x0;
      return grp;
    };
    return grp;
  };
})();
